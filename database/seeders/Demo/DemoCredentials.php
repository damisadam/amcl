<?php

namespace Database\Seeders\Demo;

use App\Models\Tenant;
use App\Models\User;
use App\Support\TenantContext;

/** Writes docs/DEMO_CREDENTIALS.md from the seeded database (local/demo only). */
final class DemoCredentials
{
    public static function write(string $path): void
    {
        $pw = DemoCatalog::PASSWORD;
        $md = "# Demo credentials\n\n> Generated by `php artisan amcl:demo-reset`. **Local / demo environments only – never use in production.**\n"
            ."> All demo passwords: `{$pw}`. Wallet PIN for demo customers: `4826`. OTPs are shown on screen in demo mode.\n\n"
            ."## Two-step verification (TOTP)\n\nPlatform users and privileged staff (Tenant Admin, approvers, finance posters, KYC/AML reviewers) must enter an authenticator code after the password. "
            ."All demo staff share the setup key `".config('security.mfa.demo_secret')."` (add it to any authenticator app as a time-based key). "
            ."In demo mode the challenge page also shows the current code in the yellow SIMULATED box. Real users enrol their own key on first sign-in.\n\n";
        $md .= "## Platform administration — http://localhost:8000/platform/login\n\n| Role | Email | Purpose |\n|---|---|---|\n"
            ."| Platform Admin | admin@platform.demo | Tenants, provisioning, health, demo tools |\n| Platform Support | support@platform.demo | Health monitoring; requests support access |\n"
            ."| Platform Admin (2nd) | security@platform.demo | Grants support access requests (no self-grant) |\n\n";
        TenantContext::bypass(function () use (&$md) {
            foreach (Tenant::orderBy('id')->get() as $t) {
                $md .= "## {$t->name} (`{$t->code}`)\n\nCustomer portal: http://localhost:8000/t/{$t->code} · Staff/vendor login: http://localhost:8000/login?org={$t->code}\n\n";
                $md .= "| Role(s) | Email | Name | Branch |\n|---|---|---|---|\n";
                foreach (User::with(['roles', 'branch'])->where('tenant_id', $t->id)->whereIn('type', ['staff', 'vendor'])->orderBy('id')->get() as $u) {
                    $roles = $u->isVendor() ? 'Vendor portal' : $u->roles->pluck('name')->join(', ');
                    $note = $u->status->value !== 'active' ? ' _(status: '.$u->status->value.')_' : '';
                    $md .= "| {$roles}{$note} | {$u->email} | {$u->name} | ".($u->branch?->name ?? '—')." |\n";
                }
                $md .= "\n**Customers** (login with email or mobile):\n\n| Email | Mobile | Scenario |\n|---|---|---|\n";
                foreach (User::with('customer')->where('tenant_id', $t->id)->where('type', 'customer')->orderBy('id')->take(30)->get() as $i => $u) {
                    $c = $u->customer;
                    $scenario = match ($i) {
                        0 => 'Registered, mobile not verified', 1 => 'Profile started, KYC not run', 2 => 'KYC manual review pending', 3 => 'KYC failed (NADRA mismatch)',
                        4 => 'AML potential match – compliance review', 5 => 'KYC passed after manual review', 6 => 'CNIC expired', 7 => 'CNIC expiring soon',
                        default => 'KYC '.$c?->kyc_status?->value.'; '.($c?->loanAccounts()->count() ? $c->loanAccounts()->count().' financing(s)' : 'no financing'),
                    };
                    $md .= "| {$u->email} | {$u->mobile} | {$scenario} |\n";
                }
                $md .= "\n";
            }
        });
        @mkdir(dirname($path), 0775, true);
        file_put_contents($path, $md);
    }
}
